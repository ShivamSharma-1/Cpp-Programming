#include <iostream>
#include <ios>

int main() {

    int posNum {717171};

    std :: cout << "-----Default positive number in lowercase-----" << std :: endl;
    std :: cout << "posNum in decimal : " << std :: dec << posNum << std :: endl;
    std :: cout << "posNum in hexagonal : " << std :: hex << posNum << std :: endl;
    std :: cout << "posNum in octal : " << std :: oct << posNum << std :: endl;

    std :: cout << std :: endl;

    std :: cout << "-----Positive number in uppercase-----" << std :: endl;
    std :: cout << std :: uppercase;
    std :: cout << "posNum in decimal : " << std :: dec << posNum << std :: endl;
    std :: cout << "posNum in hexagonal : " << std :: hex << posNum << std :: endl;
    std :: cout << "posNum in octal : " << std :: oct << posNum << std :: endl;
}