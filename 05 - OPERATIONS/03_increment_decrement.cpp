#include <iostream>
int main () {
    int value {5};

    // Increment by 1
    value = value + 1;
    std :: cout << "The value is : " << value << std :: endl;

    // Reset value to 5;
    value = 5;

    // Decreament by 1;
    value = value - 1;
    std :: cout << "The value is : " << value << std :: endl;

    return 0;
}