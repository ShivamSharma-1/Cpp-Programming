#include <iostream>
#include <cmath>

int main() {
    int a {4};
    int b {81};
    int c {100};
    int d {99};

    std :: cout << "The square root of " << a << " is : " << std :: sqrt(a) << std :: endl;
    std :: cout << "The square root of " << b << " is : " << std :: sqrt(b) << std :: endl;
    std :: cout << "The square root of " << c << " is : " << std :: sqrt(c) << std :: endl;
    std :: cout << "The square root of " << d << " is : " << std :: sqrt(d) << std :: endl;

    return 0;
}